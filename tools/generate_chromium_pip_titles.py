#!/usr/bin/env python3
"""Generate the compiled Chromium PiP title table from the frozen dataset."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

EXPECTED_SYMBOL = "IDS_PICTURE_IN_PICTURE_TITLE_TEXT"
EXPECTED_MESSAGE_ID = "7750228210027921155"
EXPECTED_SOURCE_SHA = "41020d875c4518f25b5b27a76c7d418235a50f31"
EXPECTED_SOURCE_TEXT = "Picture in picture"
EXPECTED_LOCALES = 81


def cpp_wide_literal(value: str) -> str:
    escaped: list[str] = []
    for character in value:
        codepoint = ord(character)
        if character == "\\":
            escaped.append("\\\\")
        elif character == '"':
            escaped.append('\\"')
        elif 0x20 <= codepoint <= 0x7E:
            escaped.append(character)
        elif codepoint <= 0xFFFF:
            if 0xD800 <= codepoint <= 0xDFFF:
                raise ValueError("dataset contains a surrogate code point")
            escaped.append(f"\\u{codepoint:04X}")
        elif codepoint <= 0x10FFFF:
            escaped.append(f"\\U{codepoint:08X}")
        else:
            raise ValueError("dataset contains an invalid Unicode code point")
    return 'L"' + "".join(escaped) + '"'


def validate(data: dict[str, object]) -> dict[str, str]:
    expected = {
        "symbol": EXPECTED_SYMBOL,
        "message_id": EXPECTED_MESSAGE_ID,
        "source_sha": EXPECTED_SOURCE_SHA,
        "source_text": EXPECTED_SOURCE_TEXT,
    }
    for key, value in expected.items():
        if data.get(key) != value:
            raise ValueError(f"unexpected {key}: {data.get(key)!r}")

    titles = data.get("titles")
    if not isinstance(titles, dict):
        raise ValueError("titles must be an object")
    if len(titles) != EXPECTED_LOCALES:
        raise ValueError(
            f"expected {EXPECTED_LOCALES} locale titles, found {len(titles)}"
        )
    if not all(
        isinstance(locale, str) and isinstance(title, str)
        for locale, title in titles.items()
    ):
        raise ValueError("locale titles must be strings")

    count = data.get("locale_count")
    if (
        not isinstance(count, dict)
        or count.get("available") != EXPECTED_LOCALES
        or count.get("found") != EXPECTED_LOCALES
        or count.get("missing") != []
    ):
        raise ValueError("locale_count does not describe all 81 locales")

    hashes = data.get("xtb_sha256")
    if not isinstance(hashes, dict) or set(hashes) != set(titles):
        raise ValueError("xtb_sha256 locales do not match title locales")
    return {str(locale): str(title) for locale, title in titles.items()}


def render(data: dict[str, object], dataset_sha256: str) -> str:
    titles = validate(data)
    entries = [(None, EXPECTED_SOURCE_TEXT)]
    entries.extend(titles.items())
    lines = [
        "// Generated by tools/generate_chromium_pip_titles.py. Do not edit.",
        f"// Chromium source commit: {EXPECTED_SOURCE_SHA}",
        f"// GRIT message ID: {EXPECTED_MESSAGE_ID}",
        f"// Frozen dataset SHA-256: {dataset_sha256}",
        "",
        "#pragma once",
        "",
        "#include <array>",
        "#include <string_view>",
        "",
        "namespace schiva::detail {",
        "",
        "inline constexpr std::array<std::wstring_view, "
        f"{len(entries)}> kChromiumPipOfficialTitles = {{",
    ]
    for locale, title in entries:
        label = "source" if locale is None else locale
        lines.append(f"    {cpp_wide_literal(title)},  // {label}")
    lines.extend(
        [
            "};",
            "",
            "}  // namespace schiva::detail",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify that the output already matches the generated content",
    )
    args = parser.parse_args()

    raw = args.input.read_bytes()
    data = json.loads(raw.decode("utf-8"))
    if not isinstance(data, dict):
        raise ValueError("dataset root must be an object")
    generated = render(data, hashlib.sha256(raw).hexdigest())

    if args.check:
        if not args.output.exists():
            raise FileNotFoundError(args.output)
        if args.output.read_text(encoding="utf-8") != generated:
            raise ValueError(f"{args.output} is not reproducible")
        return 0

    args.output.write_text(generated, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
